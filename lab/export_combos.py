"""Write combos.txt for the patched Forge engine (-Dreferee.combos=...): every registered deck's combos
(Commander Spellbook variants + engine/payoff pairs, as in gsim.combo_sets), key cards, no-same-turn cards and
protection spells (the list's "Protection" group), plus opponents' decisive combos from opp_combos.json.
usage: python3 export_combos.py [--price-cap 80]"""
import sys, json, argparse
ap = argparse.ArgumentParser(); ap.add_argument("--price-cap", type=float, default=80); a = ap.parse_args(); sys.argv = ["x"]
import score2 as S; S.PRICE_CAP = a.price_cap
import gsim2 as H
front = lambda n: n.split(" // ")[0]
reg = {k: v for k, v in json.load(open("decks.json")).items() if not k.startswith("_")}
lines = ["# deckName|key cards|no-same-turn cards|combo pieces   (generated by export_combos.py)"]
import re as _re
V = json.load(open("bulk/variants_small.json")); C = H.C; _full = {k.split(" // ")[0]: k for k in C}
def independent(deckset):
    """decisive, table-wide Spellbook combos made only of permanents in the deck, needing no commander"""
    out = set()
    for v in V:
        if v["cmdr"] or len(v["cards"]) > 4: continue
        cs = [front(c) for c in v["cards"]]
        if not all(c in deckset for c in cs): continue
        if any(_re.search(r"Instant|Sorcery", C.get(_full.get(c, c), {"type": "Instant"})["type"]) for c in cs): continue
        if v["dec"]:
            if all(("target opponent" in p or "target player" in p) for p in v["prod"] if any(w in p for w in ("lose", "damage", "lifeloss"))): continue
            out.add(tuple(sorted(cs)))
        else:   # infinite engine (e.g. Mazirek + Broodscale): pair it with a payoff the deck runs
            for k in S.engine_kinds(v["prod"]):
                for pay in S.PAYOFF[k]:
                    if pay in deckset and pay not in cs: out.add(tuple(sorted(cs + [pay])))
    return out
for name, r in reg.items():
    b = H.load(r["list"]); d = json.load(open(r["list"]))
    ns = ";".join(r.get("no_same_turn", []))
    keys = [front(k) for k in r["key"]]
    # key cards are listed as pieces of each commander combo, so independent combos can need no commander
    for s in b["combos"]: lines.append(f"{name}||{ns}|" + ";".join(sorted(set(front(p) for p in s) | set(keys))))
    ind = independent(set(front(n) for n in b["deck"]))
    for s in ind: lines.append(f"{name}||{ns}|" + ";".join(s))
    if ind: print(f"  {name}: +{len(ind)} independent combos: " + "; ".join(" + ".join(x) for x in sorted(ind)[:4]))
    prot = d.get("Protection", [])
    if prot: lines.append(f"PROTECT|{name}|" + ";".join(front(p) for p in prot))
    print(f"{name}: {len(b['combos'])} combos, protection {len(prot)}")
for name, combos in json.load(open("opp_combos.json")).items():
    for c in combos: lines.append(f"{name}|||" + ";".join(front(p) for p in c))
open("combos.txt", "w").write("\n".join(lines) + "\n"); print("wrote combos.txt", len(lines) - 1, "lines")
