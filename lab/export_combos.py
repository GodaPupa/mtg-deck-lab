"""Write combos.txt for the patched Forge engine (-Dreferee.combos=...): every registered deck's combos
(Commander Spellbook variants + engine/payoff pairs, as in gsim.combo_sets), key cards, no-same-turn cards and
protection spells (the list's "Protection" group), plus opponents' decisive combos from opp_combos.json.
usage: python3 export_combos.py [--price-cap 80]"""
import sys, json, argparse
ap = argparse.ArgumentParser(); ap.add_argument("--price-cap", type=float, default=80); a = ap.parse_args(); sys.argv = ["x"]
import score2 as S; S.PRICE_CAP = a.price_cap
import gsim2 as H
front = lambda n: n.split(" // ")[0]
reg = {k: v for k, v in json.load(open("decks.json")).items() if not k.startswith("_")}
lines = ["# deckName|key cards|no-same-turn cards|combo pieces   (generated by export_combos.py)"]
for name, r in reg.items():
    b = H.load(r["list"]); d = json.load(open(r["list"]))
    key = ";".join(front(k) for k in r["key"]); ns = ";".join(r.get("no_same_turn", []))
    for s in b["combos"]: lines.append(f"{name}|{key}|{ns}|" + ";".join(sorted(front(p) for p in s)))
    prot = d.get("Protection", [])
    if prot: lines.append(f"PROTECT|{name}|" + ";".join(front(p) for p in prot))
    print(f"{name}: {len(b['combos'])} combos, protection {len(prot)}")
for name, combos in json.load(open("opp_combos.json")).items():
    for c in combos: lines.append(f"{name}|||" + ";".join(front(p) for p in c))
open("combos.txt", "w").write("\n".join(lines) + "\n"); print("wrote combos.txt", len(lines) - 1, "lines")
